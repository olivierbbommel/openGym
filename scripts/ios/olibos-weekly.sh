#!/bin/bash
# The weekly update of the olibos build: upstream's latest under our changes, tested, and only
# then a new TestFlight build. Run by launchd on the Mac mini (com.olibos.opengym-weekly); by hand:
#
#   bash scripts/ios/olibos-weekly.sh             the real run
#   bash scripts/ios/olibos-weekly.sh --dry-run   everything but the upload and the push; the
#                                                 branch is put back where it was afterwards
#
#   1. refuse to start with work in progress (anything uncommitted but the generated build files)
#   2. fetch upstream; nothing new: stop, nothing built
#   3. rebase olibos onto it; a conflict: the rebase is aborted, the branch left as it was
#   4. scripts/ios/olibos-ids.sh (upstream may have added a place that names its ids)
#   5. npm ci, vitest (TZ=UTC, as upstream's CI), swift test (WatchCore)
#   6. build:mobile, the ci target scripts, archive with the next build number, upload
#   7. push the branch to the fork, only if $OUT/push-enabled exists
#
# Any failure: the branch goes back to where it was, and $OUT/weekly-report.md says what failed
# and where the full log is. Run copied out of the repository (the rebase rewrites this file).
set -uo pipefail

REPO="${OLIBOS_REPO:-$HOME/Developer/Apps-Developing/opengym}"
OUT="${OLIBOS_OUT:-$HOME/Developer/Apps-Developing/opengym-build}"
DRY=0; [ "${1:-}" = "--dry-run" ] && DRY=1
STAMP=$(date +%Y-%m-%d-%H%M)
LOG="$OUT/weekly/$STAMP.log"
REPORT="$OUT/weekly-report.md"
mkdir -p "$OUT/weekly"
export PATH="/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin:$PATH"
export LANG=en_US.UTF-8 LC_ALL=en_US.UTF-8
export GEM_PATH="/opt/homebrew/Cellar/cocoapods/1.17.0/libexec:$(gem env gempath 2>/dev/null)"
exec > >(tee -a "$LOG") 2>&1

report () {   # status, then lines
  local status="$1"; shift
  {
    echo "# OliGym weekly update: $status"
    echo
    echo "- When: $(date '+%Y-%m-%d %H:%M %Z')$([ $DRY = 1 ] && echo ' (dry run: no upload, no push, branch put back)')"
    for line in "$@"; do echo "- $line"; done
    echo "- Full log: $LOG"
  } > "$REPORT"
  echo "== $status"
}

cd "$REPO" || { report "FAILED" "No repository at $REPO"; exit 1; }
git config user.email >/dev/null || { report "FAILED" "No git author set in $REPO"; exit 1; }
[ "$(git rev-parse --abbrev-ref HEAD)" = "olibos" ] || { report "FAILED" "The checkout is not on branch olibos"; exit 1; }

# 1. Generated by every build (the ci scripts, pod install, swift test): put back, nothing else allowed.
GENERATED='^( M frontend/ios/App/App.xcodeproj/project.pbxproj|\?\? frontend/ios/App/App.xcodeproj/xcshareddata/|\?\? frontend/ios/App/App.xcworkspace/contents.xcworkspacedata|\?\? frontend/ios/App/Podfile.lock|\?\? frontend/ios/App/WatchCore/.build/)$'
OTHER=$(git status --porcelain | grep -Ev "$GENERATED")
if [ -n "$OTHER" ]; then report "STOPPED" "Work in progress in the checkout, not touched:" "$(echo "$OTHER" | tr '\n' ' ')"; exit 1; fi
git checkout -- frontend/ios/App/App.xcodeproj/project.pbxproj

OLD=$(git rev-parse HEAD)
restore () { git rebase --abort >/dev/null 2>&1; git reset -q --hard "$OLD"; }

# 2.
git fetch -q origin main || { report "FAILED" "Could not fetch upstream (network?)"; exit 1; }
UP=$(git rev-parse origin/main)
BASE=$(git merge-base HEAD origin/main)
NEW=$(git rev-list --count "$BASE..$UP")
if [ "$NEW" = 0 ] && [ $DRY = 0 ]; then report "NOTHING NEW" "Upstream has nothing since the last update ($(git log -1 --format='%h %s' "$UP"))."; exit 0; fi
UPLOG=$(git log --format='%h %s' "$BASE..$UP" | head -15 | sed 's/^/  /')

# 3.
if ! git rebase -q origin/main; then
  CONFLICTS=$(git diff --name-only --diff-filter=U | tr '\n' ' ')
  restore
  report "CONFLICT" "Upstream's $NEW new commit(s) conflict with ours in: $CONFLICTS" "The branch is left as it was ($OLD). This needs a hand: ask Claude to rebase by hand." "Upstream's new commits:" "$UPLOG"
  exit 1
fi

fail () { local what="$1"; restore; report "FAILED" "$what" "The branch is left as it was ($OLD)." "Upstream's new commits:" "$UPLOG"; exit 1; }

# 4.
sh scripts/ios/olibos-ids.sh || fail "olibos-ids.sh: upstream names its ids somewhere new (see the log)"
if [ -n "$(git status --porcelain --untracked-files=no | grep -Ev "$GENERATED")" ]; then
  git commit -qam "ios: own bundle IDs on upstream's newer files" || fail "Could not commit the renamed ids"
fi

# 5.
(cd frontend && npm ci --no-audit --no-fund) || fail "npm ci failed"
(cd frontend && TZ=UTC NODE_OPTIONS=--no-experimental-webstorage npx vitest run) || fail "The phone tests (vitest) failed"
(cd frontend/ios/App/WatchCore && swift test) || fail "The Watch tests (swift test) failed"

# 6.
(cd frontend && npm run build:mobile) || fail "npm run build:mobile failed"
for s in add-asset-downloader add-watch-app add-widgets; do (cd frontend && ruby "ios/ci/$s.rb") || fail "ios/ci/$s.rb failed"; done
LAST=$(ruby "$OUT/asc.rb" GET "/v1/builds?filter[app]=6827019065&sort=-uploadedDate&limit=20&fields[builds]=version" 2>/dev/null | tail -n +2 \
  | ruby -rjson -e 'puts (JSON.parse(STDIN.read)["data"] || []).map { |b| b["attributes"]["version"].to_i }.max || 0' 2>/dev/null)
[ -n "$LAST" ] && [ "$LAST" -gt 0 ] 2>/dev/null || fail "Could not read the last build number from App Store Connect"
NUM=$((LAST + 1))
VERSION=$(grep -m1 -o 'MARKETING_VERSION = [^;]*' frontend/ios/App/App.xcodeproj/project.pbxproj | sed 's/.*= //')
ARCHIVE="$OUT/OliGym-$NUM.xcarchive"
if [ $DRY = 1 ]; then
  (cd frontend/ios/App && xcodebuild -workspace App.xcworkspace -scheme App -configuration Debug -destination 'generic/platform=iOS Simulator' \
    -derivedDataPath "$OUT/dd" CODE_SIGNING_ALLOWED=NO build -quiet) || fail "The simulator build failed"
  RESULT="Simulator build passed; a real run would upload $VERSION ($NUM)"
else
  (cd frontend/ios/App && xcodebuild -workspace App.xcworkspace -scheme App -configuration Release -destination 'generic/platform=iOS' \
    -archivePath "$ARCHIVE" -derivedDataPath "$OUT/dd-release" DEVELOPMENT_TEAM=MH28FR6W5Y CODE_SIGN_STYLE=Automatic \
    CURRENT_PROJECT_VERSION=$NUM -allowProvisioningUpdates archive -quiet) || fail "The archive failed"
  xcodebuild -exportArchive -archivePath "$ARCHIVE" -exportOptionsPlist "$OUT/ExportOptions.plist" -exportPath "$OUT/export-$NUM" \
    -allowProvisioningUpdates || fail "The upload to App Store Connect failed"
  RESULT="Uploaded $VERSION ($NUM) to TestFlight; the Me group gets it once Apple has processed it (about 10 minutes)"
fi

# 7.
PUSHED="Not pushed (no $OUT/push-enabled)"
if [ $DRY = 0 ] && [ -f "$OUT/push-enabled" ]; then
  if git push -q --force-with-lease fork olibos; then PUSHED="Pushed olibos to the fork"; else PUSHED="The push to the fork FAILED (the build is uploaded; push by hand)"; fi
fi

if [ $DRY = 1 ]; then restore; fi
report "OK" "Upstream: $NEW new commit(s), now on $(git log -1 --format='%h' "$UP")" "$RESULT" "$PUSHED" "Branch olibos: $([ $DRY = 1 ] && echo "put back at $OLD" || git log -1 --format='%h')" "Upstream's new commits:" "$UPLOG"
